import { describe, test, expect } from 'vitest';
import { looksLikeRefusal, hasSimplifiedChars } from '../autoTitle';

// 這支的風險是**不對稱**的：
//   漏抓一句模型的廢話 → 下一則訊息還會再試，影響很小
//   誤殺一個合法標題   → 那個主題永遠沒有名字，而且每則訊息都白呼叫一次 Haiku
//
// 第一版寫成 /無法/、/不能/、/對不起/ 這種單字比對，在關係諮詢產品裡
// 等於把最典型的諮詢主題全擋掉（「無法跟婆婆溝通」「他從不說對不起」）。
// 所以「必須放行」那一組才是這支測試真正要守的東西。

describe('looksLikeRefusal — 模型在推託的句子', () => {
  test.each([
    '無法判斷諮詢主題',
    '無法確定諮詢主題',
    '無法產生標題',
    '抱歉我無法提供標題',
    '很抱歉，這句話沒有具體內容',
    '沒有足夠的資訊可以下標',
    '缺乏上下文',
    '難以判斷主題',
    '請提供更多資訊',
    '需要更多內容才能判斷',
    'Sorry, I cannot determine a topic',
  ])('擋下：%s', (text) => {
    expect(looksLikeRefusal(text)).toBe(true);
  });
});

describe('looksLikeRefusal — 合法的諮詢主題標題（誤殺代價最高）', () => {
  test.each([
    // 「無法 / 不能 / 難以 / 沒辦法」是這個產品的日常字眼
    '無法跟婆婆溝通',
    '老公無法理解我',
    '無法拒絕媽媽的要求',
    '他說我不能出門',
    '不能說的話越來越多',
    '難以開口說真心話',
    '沒辦法原諒他',
    // 「抱歉 / 對不起」同理
    '他從不說對不起',
    '老公從不抱歉',
    // 「需要更多 / 請 / 沒有」後面接的是感受，不是資訊
    '需要更多陪伴',
    '孩子需要更多空間',
    '請他多陪我一點',
    '沒有共同話題',
    // 一般標題
    '兒子玩手機、成績下滑',
    '開刀後不聽勸、到處跑',
  ])('放行：%s', (text) => {
    expect(looksLikeRefusal(text)).toBe(false);
  });
});

// ── 繁體檢查 ────────────────────────────────────────────
//
// 正式站出現過「术后不听医嘱、丈夫四处奔波、妻子无法劝阻」——
// 使用者輸入的原文全是繁體，是模型自己轉成簡體的。
// autoTitle 的 prompt 原本只寫「中文字」，沒有像 buildContext 那樣寫明「繁體中文」。
//
// 偵測只用來決定「要不要重試」，不做轉換。誤判成簡體的代價是多一次 Haiku 呼叫；
// 漏判的代價是簡體字寫進 DB、使用者直接看到 —— 所以寧可寬一點。

describe('hasSimplifiedChars — 該抓到的簡體', () => {
  test.each([
    '术后不听医嘱、丈夫四处奔波、妻子无法劝阻',
    '儿子玩手机、成绩下滑',
    '老婆冷战、不肯讲话',
    '无法沟通',
    '妈妈总是干涉',
  ])('抓到：%s', (text) => {
    expect(hasSimplifiedChars(text)).toBe(true);
  });
});

describe('hasSimplifiedChars — 繁體標題不可誤判', () => {
  test.each([
    '術後不聽醫囑、丈夫四處奔波、妻子無法勸阻',
    '兒子玩手機、成績下滑',
    '老婆冷戰、不肯講話',
    '無法跟婆婆溝通',
    '開刀後不聽勸、到處跑',
    '主管不信任、micromanage',
    '媽媽總是干涉',
    '他從不說對不起',
    // ── 兩邊都合法的字，不可以被當成簡體 ──
    // 這幾個是第一版真的誤收、被這支測試抓出來的（里 谷 斗 划 淀）。
    // 判準：這個字在繁體文章裡會不會單獨出現？會的話就不能進字元集。
    '皇后的心事',
    '鄰里關係緊張',
    '公里數算不清',
    '山谷裡的回音',
    '划船時吵起來',
    '一斗米的爭執',
    '沉淀一下再談',
  ])('放行：%s', (text) => {
    expect(hasSimplifiedChars(text)).toBe(false);
  });
});
